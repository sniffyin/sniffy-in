/**
 * Per-page "last updated" tracking for the generated SEO pages.
 *
 * Each generator builds its HTML with two placeholders in it (LM_ISO, LM_HUMAN)
 * and hands it to stampPage(). The placeholder-form HTML is hashed and compared
 * with scripts/.page-hashes.json:
 *   - same hash  -> the page did not change; keep its recorded date
 *   - new hash   -> the page changed; its date becomes today
 * so a page's date moves exactly when its generated output changes (copy,
 * prices, schema, markup) and never otherwise — independent of git history,
 * CI clone depth or build time. Commit both manifests with the regenerated HTML.
 *
 * Dates go to src/data/pageDates.generated.ts so React pages can show the same
 * value; call flushPageDates() once at the end of each generator.
 */
import crypto from 'crypto'
import fs from 'fs'
import path from 'path'
import { formatPageDate } from '../src/data/pageDates.ts'

export const LM_ISO = '@@LM_ISO@@'
export const LM_HUMAN = '@@LM_HUMAN@@'

const HASHES = path.join(process.cwd(), 'scripts/.page-hashes.json')
const DATES = path.join(process.cwd(), 'src/data/pageDates.generated.ts')

const readJson = (f: string): Record<string, string> => {
  try {
    return JSON.parse(fs.readFileSync(f, 'utf8'))
  } catch {
    return {}
  }
}

const hashes = readJson(HASHES)
const dates: Record<string, string> = (() => {
  try {
    const src = fs.readFileSync(DATES, 'utf8')
    return Object.fromEntries([...src.matchAll(/'([^']+)': '([\d-]+)'/g)].map((m) => [m[1], m[2]]))
  } catch {
    return {}
  }
})()

// India calendar date, pinned to IST rather than the machine's timezone, so a
// CI server running in UTC stamps the same day as a laptop in Pune. (UTC alone
// would give the previous day between 00:00 and 05:30 IST.)
const today = () => new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' })

/** Returns the date a page would be stamped with, recording it if the page changed. */
export function stampPage(key: string, htmlWithPlaceholders: string): string {
  const hash = crypto.createHash('sha1').update(htmlWithPlaceholders).digest('hex')
  if (hashes[key] !== hash || !dates[key]) {
    hashes[key] = hash
    dates[key] = today()
  }
  const iso = dates[key]
  return htmlWithPlaceholders.split(LM_ISO).join(iso).split(LM_HUMAN).join(formatPageDate(iso))
}

/**
 * Date-only variant for pages that are not generated HTML (the home page is
 * assembled at build time by prerenderSpa.ts, around a shell whose asset hashes
 * change every build). Hash just the content you pass in; returns the ISO date.
 */
export function stampDate(key: string, content: string): string {
  const hash = crypto.createHash('sha1').update(content).digest('hex')
  if (hashes[key] !== hash || !dates[key]) {
    hashes[key] = hash
    dates[key] = today()
  }
  return dates[key]
}

export function flushPageDates(): void {
  const sortedKeys = Object.keys(dates).sort()
  const sortedHashes = Object.fromEntries(Object.keys(hashes).sort().map((k) => [k, hashes[k]]))
  const hashOut = JSON.stringify(sortedHashes, null, 2) + '\n'
  const dateOut = `/**
 * GENERATED by scripts/pageDates.ts — do not edit by hand.
 * A page's date changes only when its generated HTML changes.
 */
export const PAGE_DATES = {
${sortedKeys.map((k) => `  '${k}': '${dates[k]}',`).join('\n')}
} as const;
`
  if (!fs.existsSync(HASHES) || fs.readFileSync(HASHES, 'utf8') !== hashOut) fs.writeFileSync(HASHES, hashOut)
  if (!fs.existsSync(DATES) || fs.readFileSync(DATES, 'utf8') !== dateOut) fs.writeFileSync(DATES, dateOut)
}
