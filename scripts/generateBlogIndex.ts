/**
 * scripts/generateBlogIndex.ts → src/data/blogIndex.ts
 *
 * blogPosts.ts holds every article body (~370 KB). RelatedArticles needs only
 * slug/title/category/readTime/audience, but importing blogPosts put the whole
 * file into the shared chunk that every locality and hub page loads before
 * React can paint the hero (the LCP element). blogIndex.ts is that metadata
 * alone. Generated so the two can't drift; `build`/`generate-all` re-run it.
 */
import fs from 'fs'
import path from 'path'
import { blogPosts } from '../src/data/blogPosts.ts'

const entries = blogPosts.map(({ slug, title, category, readTime, audience }) => ({
  slug, title, category, readTime, audience,
}))

const out = `// AUTO-GENERATED by scripts/generateBlogIndex.ts — do not edit by hand.
// Metadata-only view of blogPosts.ts, small enough for the critical path.
import type { BlogAudience } from './blogPosts'

export type BlogIndexEntry = {
  slug: string
  title: string
  category: string
  readTime: string
  audience: BlogAudience
}

export const blogIndex: BlogIndexEntry[] = ${JSON.stringify(entries, null, 2)}
`

fs.writeFileSync(path.resolve(import.meta.dirname, '../src/data/blogIndex.ts'), out)
console.log(`blogIndex.ts: ${entries.length} posts`)
